/**
 * 节气、农历字面量、公历分界这一路的定点体检。
 *
 *   node bench-22/probe-solar-terms.mjs
 *
 * 为什么单独一个探针：这一路错起来**没有任何症状**。把清明写死成 4 月 5 日，
 * 2024 年的「清明前一天」就早一天，不会报错、日志干净、读数也不会动——四套题里
 * 没有一道踩到它。`probe-festive-days.mjs` 钉的是春节族和节日窗口，节气一个都没有。
 *
 * 钉六件事：
 *   1. **2027 年二十四个节气**逐个对公布日期（`Intl` 没有节气，只能按官方历表抄）；
 *   2. **清明不是固定 4 月 5 日**：2020、2024、2028 都在 4 月 4 日；
 *   3. **农历月名的口语形式**：「八月十五」「二月初八」「十月初一」不带「农历」前缀
 *      也要认（以前只认正月/腊月/冬月）；
 *   4. **公历不能被抢走**：「十二月十五号」是公历 12 月 15 日，不是腊月十五；
 *   5. **歧义词不许自动当节气**：「小满」「雨水」「大雪」不带「那天/前后」时，
 *      一个日期都不许产出来（「小满」在 2.2 的语料里出现 1562 次，全是人名）；
 *   6. **腊月三十就是除夕**：腊月只有二十九天时「三十」不存在，以前会一路跳到
 *      下一个有三十的腊月（2026-11-13 问，答案是 2030-02-02）。
 *
 * 公布日期在这里**独立抄一遍**，不从 `lib/index.js` 引。探针的价值在独立声明；
 * 引用被测对象自己的表，等于自己证明自己。
 */
import { parseDue } from '../lib/index.js';

const ZONE = 'Asia/Shanghai';
const BASE = Date.parse('2026-11-13T10:00:00+08:00');

let pass = 0;
let fail = 0;
const bad = [];
const ok = (name) => {
	pass += 1;
};
const no = (name, detail) => {
	fail += 1;
	bad.push(`${name} —— ${detail}`);
};
const check = (name, got, want) => (got === want ? ok(name) : no(name, `得到 ${got}，应为 ${want}`));

/** 二十四个节气名，用来判断「这个日期是节气给的吗」。 */
const SOLAR = new Set(['小寒', '大寒', '立春', '雨水', '惊蛰', '春分', '清明', '谷雨', '立夏', '小满', '芒种', '夏至', '小暑', '大暑', '立秋', '处暑', '白露', '秋分', '寒露', '霜降', '立冬', '小雪', '大雪', '冬至']);
const ymd = (ts) => (ts === void 0 || ts === null ? '—' : new Intl.DateTimeFormat('sv-SE', { timeZone: ZONE, dateStyle: 'short' }).format(new Date(ts)));
const due = (text, base = BASE) => {
	const hit = parseDue(text, base, ZONE, { festive: true });
	return hit === void 0 ? null : hit;
};

/** 2027 年二十四个节气，香港天文台逐日对照表。独立抄写。 */
const TERMS_2027 = {
	小寒: '01-05', 大寒: '01-20', 立春: '02-04', 雨水: '02-19',
	惊蛰: '03-06', 春分: '03-21', 清明: '04-05', 谷雨: '04-20',
	立夏: '05-06', 小满: '05-21', 芒种: '06-06', 夏至: '06-21',
	小暑: '07-07', 大暑: '07-23', 立秋: '08-08', 处暑: '08-23',
	白露: '09-08', 秋分: '09-23', 寒露: '10-08', 霜降: '10-23',
	立冬: '11-07', 小雪: '11-22', 大雪: '12-07', 冬至: '12-22',
};

/* ① 2027 年逐条。一年之内问，每个节气都要落在公布日期那一天。 */
const from2027 = Date.parse('2027-01-01T08:00:00+08:00');
for (const [name, want] of Object.entries(TERMS_2027)) {
	/* 加「那天」是为了给歧义词（小雪、大雪、白露、雨水、小满）一个明确的日期语境，
	 * 其余十四个字不加也一样——统一写法让这条断言量的只有日期，不是触发条件。 */
	const hit = due(`${name}那天`, from2027);
	check(`2027 ${name}`, hit === null ? '—' : ymd(hit.from).slice(5), want);
}

/* ② 清明浮动。2020–2060 里有二十六年不在 4 月 5 日。 */
for (const [year, want] of [[2020, '04-04'], [2024, '04-04'], [2028, '04-04'], [2027, '04-05'], [2030, '04-05']]) {
	const at = Date.parse(`${year}-01-01T08:00:00+08:00`);
	const hit = due('清明前一周要请假', at);
	check(`清明 ${year}`, hit === null ? '—' : ymd(hit.from).slice(5), want === '04-05' ? '03-29' : '03-28');
}

/* ③ 农历月名的口语形式：不带「农历」两个字。 */
const LUNAR = [
	['腊月二十八，我要回娘家', '2027-02-04'],
	['八月十五回家吃饭', '2027-09-15'],
	['二月初八要去看展', '2027-03-15'],
	['六月初六晒被子', '2027-07-09'],
	['十月初一上坟', '2027-10-29'],
	['三月初三上巳', '2027-04-09'],
	['农历八月十六', '2027-09-16'],
];
for (const [text, want] of LUNAR) {
	const hit = due(text);
	check(`农历字面量「${text}」`, hit === null ? '—' : ymd(hit.from), want);
}

/* ④ 公历不能被农历抢走。这两条以前是「农历三月初十」和「农历八月十」，差五天。 */
check('公历「十二月十五号」', ymd(due('十二月十五号体检')?.from), '2026-12-15');
check('公历「十二月十五号」不许是农历', due('十二月十五号体检')?.precision !== 'day' || ymd(due('十二月十五号体检')?.from) === '2026-12-15', true);

/* ⑤ 歧义词不带日期语境时，**不许被读成节气**。
 *
 * 注意判据不是「一个日期都不许产出」：「小满今天怎么样」里 `resolveDue` 会把「今天」
 * 解出来，那是它对的地方，跟节气无关。要钉的是 phrase —— 它不许是那个节气名。
 */
for (const text of ['小满今天怎么样', '雨下得挺大，雨水多', '大雪，路滑', '白露过了就凉了', '小雪这天真冷']) {
	const hit = due(text);
	check(`歧义「${text}」不认成节气`, hit !== null && SOLAR.has(hit.phrase) ? `${hit.phrase} ${ymd(hit.from)}` : '—', '—');
}
/* 反过来，带「那天」就要认。 */
check('「小满那天」要认', ymd(due('小满那天回老家')?.from), '2027-05-21');
check('「大雪那天」要认', ymd(due('大雪那天要出门')?.from), '2026-12-07');

/* ⑥ 腊月三十 = 除夕。2027 年腊月只有二十九天。 */
check('腊月三十（29 天的腊月）', ymd(due('腊月三十贴春联')?.from), '2027-02-05');
{
	/* 2026 年腊月也是二十九天（2027-02-05 是除夕），所以这一条同时钉住
	 * 「不会跳到下一个有三十的腊月」。 */
	const hit = due('腊月三十贴春联');
	check('腊月三十不许跳到 2030', hit !== null && ymd(hit.from).startsWith('2027-'), true);
}

/* ⑦ 春节族的表外年份：`SPRING_FESTIVAL` 只到 2035，2022 与 2036 走月首表。 */
for (const [year, want] of [[2022, '2022-01-31'], [2026, '2026-02-16'], [2027, '2027-02-05'], [2036, '2036-01-27']]) {
	const at = Date.parse(`${year}-01-01T08:00:00+08:00`);
	check(`除夕 ${year}`, ymd(due('除夕得早点回去', at)?.from), want);
}

if (fail > 0) {
	console.error(`✗ ${fail} 项失败（共 ${pass + fail} 项）：`);
	for (const one of bad) console.error(`  ${one}`);
	process.exit(1);
}
console.log(`✓ ${pass} 项全部通过`);
